// Growth Item 생성 로직 구현.
// 거부 표본추출(rejection sampling) 방식으로 빈칸을 골라 셀 값 5 를 둔다.
// =============================================================================
#include "GrowthItem.h"
#include "map.h"
#include <cstdlib>

void GrowthItem::generate(int stage_num) {
    // 벽/다른 아이템/스네이크 몸 등 이미 무언가 있는 칸을 침범하지 않도록
    // 빈칸(0) 이 나올 때까지 좌표를 다시 뽑는다. 30x30 맵에서 빈칸 비중이
    // 압도적이라 평균 시도 횟수는 매우 적다.
    int gx, gy;
    do {
        gx = rand() % 30;
        gy = rand() % 30;
    } while (map[stage_num][gy][gx] != 0);

    map[stage_num][gy][gx] = 5;
}